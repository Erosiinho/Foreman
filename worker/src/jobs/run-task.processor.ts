import path from 'node:path';
import GithubClient from '../github/client';
import * as git from '../lib/git';
import { createPullRequest } from '../lib/gh';
import { runClaude } from '../lib/claude';
import { readProjectConfig } from '../lib/project-config';
import { runSetupCommand } from '../lib/setup';
import ControlBus from '../queue/control-bus';
import { Notifier } from '../lib/telegram';
import IRunTaskJob from '../types/IRunTaskJob';

const sessionIdComment = (sessionId: string) => `<!-- foreman:session_id=${sessionId} -->`;

export type RunOutcome = 'done' | 'paused' | 'cancelled';

export interface ProcessorDeps {
    github: GithubClient;
    projectsRoot: string;
    controlBus: ControlBus;
    notify: Notifier;
    runTimeoutMs: number;
}

type Interruption = 'pause' | 'cancel' | 'timeout';

/**
 * Runs the git/PR flow, plus pause/resume and timeout/cancel handling. `pause` and `cancel` resolve
 * the job (BullMQ sees it as completed, not failed) — they're a deliberate stop, not an error. Only
 * a genuine failure (including a timeout) rejects.
 */
export function createRunTaskProcessor({ github, projectsRoot, controlBus, notify, runTimeoutMs }: ProcessorDeps) {
    return async function runTaskProcessor(job: IRunTaskJob): Promise<RunOutcome> {
        const { owner, repo, issueNumber, title, description, resumeSessionId } = job;
        const cwd = path.join(projectsRoot, repo);
        const branch = git.branchName(issueNumber, title);

        await github.setStatus(owner, repo, issueNumber, 'in-progress');

        const controller = new AbortController();
        let interruption: Interruption | undefined;
        let latestSessionId = resumeSessionId;

        const unsubscribe = controlBus.subscribe(owner, repo, (message) => {
            if (message.issueNumber !== issueNumber) return;
            interruption = message.action;
            controller.abort();
        });

        let effectiveTimeoutMs = runTimeoutMs;
        let timer: NodeJS.Timeout | undefined;
        const armTimeout = (ms: number) => {
            effectiveTimeoutMs = ms;
            timer = setTimeout(() => {
                interruption = 'timeout';
                controller.abort();
            }, ms);
        };
        armTimeout(runTimeoutMs);

        try {
            if (resumeSessionId) {
                await git.checkoutExisting(cwd, branch);
            } else {
                await git.checkoutBranch(cwd, branch);
            }

            // .foreman.json (per-project settings) — read post-checkout so a task branch that edits
            // its own config takes effect for its own run.
            const config = await readProjectConfig(cwd);
            if (config.timeoutMinutes) {
                clearTimeout(timer);
                armTimeout(config.timeoutMinutes * 60_000);
            }
            if (config.setup && !resumeSessionId) {
                await runSetupCommand(cwd, config.setup, controller.signal);
            }

            const { sessionId, summary } = await runClaude(cwd, description, {
                resumeSessionId,
                signal: controller.signal,
                env: config.env,
                onSessionId: (id) => {
                    latestSessionId = id;
                },
            });

            await git.commitAll(cwd, `task-${issueNumber}: ${summary.slice(0, 72)}`);
            await git.push(cwd, branch);
            const prUrl = await createPullRequest(
                cwd,
                `Task ${issueNumber}: ${title}`,
                `Auto-generated by Claude Code — see issue #${issueNumber}`,
            );

            const commentLines = [`PR: ${prUrl}`];
            if (sessionId) commentLines.push(sessionIdComment(sessionId));
            await github.addComment(owner, repo, issueNumber, commentLines.join('\n\n'));
            await github.setStatus(owner, repo, issueNumber, 'done');
            await notify(`✅ Task #${issueNumber} done — ${title}\n${prUrl}`);
            return 'done';
        } catch (err) {
            if (interruption === 'pause') {
                if (latestSessionId) {
                    await github
                        .addComment(owner, repo, issueNumber, sessionIdComment(latestSessionId))
                        .catch(() => undefined);
                }
                await github.setStatus(owner, repo, issueNumber, 'paused');
                return 'paused';
            }

            if (interruption === 'cancel') {
                await git.discardAndDeleteBranch(cwd, branch);
                await github.setStatus(owner, repo, issueNumber, 'cancelled');
                return 'cancelled';
            }

            const message =
                interruption === 'timeout'
                    ? `Run timed out after ${Math.round(effectiveTimeoutMs / 60000)} minutes`
                    : err instanceof Error
                      ? err.message
                      : String(err);
            await github
                .addComment(owner, repo, issueNumber, `Run failed:\n\n\`\`\`\n${message}\n\`\`\``)
                .catch(() => undefined);
            await github.setStatus(owner, repo, issueNumber, 'failed');
            await notify(`❌ Task #${issueNumber} failed — ${title}\n${message}`);
            throw err;
        } finally {
            clearTimeout(timer);
            unsubscribe();
        }
    };
}
